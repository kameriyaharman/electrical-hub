-- Electrical Hub — MySQL schema (MySQL 5.7+ / MariaDB 10.3+)
SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS admins (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(150) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role VARCHAR(30) NOT NULL DEFAULT 'super_admin',
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS settings (
  k VARCHAR(80) PRIMARY KEY,
  v TEXT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS cities (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  state VARCHAR(100) NOT NULL DEFAULT '',
  lat DECIMAL(10,7) NULL,
  lng DECIMAL(10,7) NULL,
  active TINYINT(1) NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS areas (
  id INT AUTO_INCREMENT PRIMARY KEY,
  city_id INT NOT NULL,
  name VARCHAR(120) NOT NULL,
  pincode VARCHAR(10) NULL,
  INDEX (city_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS users (
  id INT AUTO_INCREMENT PRIMARY KEY,
  mobile VARCHAR(15) NOT NULL UNIQUE,
  name VARCHAR(120) NULL,
  city_id INT NULL,
  role VARCHAR(20) NOT NULL DEFAULT 'customer',
  status VARCHAR(20) NOT NULL DEFAULT 'active',
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  last_login DATETIME NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS otps (
  mobile VARCHAR(15) PRIMARY KEY,
  code VARCHAR(6) NOT NULL,
  expires_at DATETIME NOT NULL,
  attempts INT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS api_tokens (
  token CHAR(64) PRIMARY KEY,
  user_id INT NOT NULL,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  INDEX (user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS categories (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  parent_id INT NULL,
  icon VARCHAR(20) NULL,
  image VARCHAR(255) NULL,
  sort INT NOT NULL DEFAULT 0,
  active TINYINT(1) NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS brands (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  categories VARCHAR(255) NULL,
  logo VARCHAR(255) NULL,
  active TINYINT(1) NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS shops (
  id INT AUTO_INCREMENT PRIMARY KEY,
  owner_user_id INT NULL,
  name VARCHAR(150) NOT NULL,
  owner_name VARCHAR(120) NULL,
  mobile VARCHAR(15) NOT NULL,
  whatsapp VARCHAR(15) NULL,
  gstin VARCHAR(20) NULL,
  shop_type VARCHAR(20) NOT NULL DEFAULT 'Retail',
  is_service TINYINT(1) NOT NULL DEFAULT 0,
  address VARCHAR(255) NULL,
  city_id INT NULL,
  area VARCHAR(120) NULL,
  pincode VARCHAR(10) NULL,
  lat DECIMAL(10,7) NULL,
  lng DECIMAL(10,7) NULL,
  open_time VARCHAR(5) NOT NULL DEFAULT '09:00',
  close_time VARCHAR(5) NOT NULL DEFAULT '21:00',
  weekly_off VARCHAR(10) NULL,
  rating DECIMAL(2,1) NOT NULL DEFAULT 0,
  review_count INT NOT NULL DEFAULT 0,
  status VARCHAR(20) NOT NULL DEFAULT 'pending',
  reject_reason VARCHAR(255) NULL,
  mobile_verified TINYINT(1) NOT NULL DEFAULT 0,
  plan VARCHAR(20) NOT NULL DEFAULT 'free',
  plan_expiry DATE NULL,
  views INT NOT NULL DEFAULT 0,
  calls INT NOT NULL DEFAULT 0,
  whatsapp_clicks INT NOT NULL DEFAULT 0,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX (city_id), INDEX (status), INDEX (owner_user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS shop_categories (
  shop_id INT NOT NULL, category_id INT NOT NULL,
  PRIMARY KEY (shop_id, category_id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS shop_brands (
  shop_id INT NOT NULL, brand_id INT NOT NULL,
  PRIMARY KEY (shop_id, brand_id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS shop_photos (
  id INT AUTO_INCREMENT PRIMARY KEY,
  shop_id INT NOT NULL,
  path VARCHAR(255) NOT NULL,
  label VARCHAR(60) NULL,
  lat DECIMAL(10,7) NULL,
  lng DECIMAL(10,7) NULL,
  distance_m INT NULL,
  source VARCHAR(20) NOT NULL DEFAULT 'camera',
  taken_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  INDEX (shop_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS products (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(200) NOT NULL,
  category_id INT NULL,
  brand_id INT NULL,
  unit VARCHAR(40) NULL,
  min_price INT NOT NULL DEFAULT 0,
  max_price INT NOT NULL DEFAULT 0,
  image VARCHAR(255) NULL,
  active TINYINT(1) NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS shop_products (
  shop_id INT NOT NULL, product_id INT NOT NULL, price INT NULL,
  PRIMARY KEY (shop_id, product_id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS offers (
  id INT AUTO_INCREMENT PRIMARY KEY,
  shop_id INT NOT NULL,
  title VARCHAR(150) NOT NULL,
  description VARCHAR(500) NULL,
  valid_till DATE NULL,
  active TINYINT(1) NOT NULL DEFAULT 1,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS plans (
  id INT AUTO_INCREMENT PRIMARY KEY,
  code VARCHAR(20) NOT NULL UNIQUE,
  name VARCHAR(60) NOT NULL,
  tagline VARCHAR(100) NULL,
  price INT NOT NULL DEFAULT 0,
  duration_days INT NOT NULL DEFAULT 30,
  photos_limit INT NOT NULL DEFAULT 5,
  search_position VARCHAR(40) NOT NULL DEFAULT 'Normal',
  home_banner TINYINT(1) NOT NULL DEFAULT 0,
  quote_priority VARCHAR(20) NOT NULL DEFAULT 'Normal',
  features TEXT NULL,
  sort INT NOT NULL DEFAULT 0,
  active TINYINT(1) NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS subscriptions (
  id INT AUTO_INCREMENT PRIMARY KEY,
  shop_id INT NOT NULL,
  plan_code VARCHAR(20) NOT NULL,
  area VARCHAR(120) NULL,
  start_date DATE NULL,
  expiry_date DATE NULL,
  amount INT NOT NULL DEFAULT 0,
  status VARCHAR(20) NOT NULL DEFAULT 'pending',
  payment_id INT NULL,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  INDEX (shop_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS banners (
  id INT AUTO_INCREMENT PRIMARY KEY,
  title VARCHAR(150) NOT NULL,
  subtitle VARCHAR(150) NULL,
  image VARCHAR(255) NULL,
  shop_id INT NULL,
  city_id INT NULL,
  start_date DATE NULL,
  end_date DATE NULL,
  amount INT NOT NULL DEFAULT 0,
  status VARCHAR(20) NOT NULL DEFAULT 'active',
  sort INT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS payments (
  id INT AUTO_INCREMENT PRIMARY KEY,
  shop_id INT NULL,
  purpose VARCHAR(60) NOT NULL,
  amount INT NOT NULL,
  method VARCHAR(30) NOT NULL DEFAULT 'UPI',
  reference VARCHAR(100) NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'pending',
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS quote_requests (
  id INT AUTO_INCREMENT PRIMARY KEY,
  code VARCHAR(20) NULL,
  user_id INT NULL,
  customer_name VARCHAR(120) NULL,
  customer_mobile VARCHAR(15) NULL,
  items TEXT NOT NULL,
  attachment VARCHAR(255) NULL,
  area VARCHAR(150) NULL,
  city_id INT NULL,
  lat DECIMAL(10,7) NULL,
  lng DECIMAL(10,7) NULL,
  send_count INT NOT NULL DEFAULT 5,
  verified_only TINYINT(1) NOT NULL DEFAULT 1,
  status VARCHAR(20) NOT NULL DEFAULT 'open',
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  INDEX (user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS quote_recipients (
  quote_id INT NOT NULL,
  shop_id INT NOT NULL,
  reply_amount INT NULL,
  reply_note VARCHAR(255) NULL,
  delivery VARCHAR(60) NULL,
  replied_at DATETIME NULL,
  PRIMARY KEY (quote_id, shop_id),
  INDEX (shop_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS reviews (
  id INT AUTO_INCREMENT PRIMARY KEY,
  shop_id INT NOT NULL,
  user_id INT NULL,
  customer_name VARCHAR(120) NULL,
  rating TINYINT NOT NULL,
  body VARCHAR(1000) NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'active',
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  INDEX (shop_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS saved_shops (
  user_id INT NOT NULL, shop_id INT NOT NULL,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (user_id, shop_id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS leads (
  id INT AUTO_INCREMENT PRIMARY KEY,
  shop_id INT NOT NULL,
  user_id INT NULL,
  type VARCHAR(20) NOT NULL,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  INDEX (shop_id), INDEX (created_at)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS searches (
  id INT AUTO_INCREMENT PRIMARY KEY,
  term VARCHAR(150) NULL,
  category_id INT NULL,
  city_id INT NULL,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  INDEX (category_id), INDEX (created_at)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS notifications (
  id INT AUTO_INCREMENT PRIMARY KEY,
  user_id INT NULL,
  title VARCHAR(150) NOT NULL,
  body VARCHAR(500) NULL,
  is_read TINYINT(1) NOT NULL DEFAULT 0,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  INDEX (user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
